class GenericPack(KnowledgePack):
    """Catch-all pack for requirements without a dedicated domain generator."""

    domain = "generic"

    @classmethod
    def matches(cls, text: str) -> bool:
        # The generic pack is the explicit fallback; the provider only reaches it
        # when nothing else matched, so it always accepts.
        return True

    def architecture(self, analysis: AnalysisResult) -> Architecture:
        return Architecture(
            overview=(
                "A layered scaffold: a framework-agnostic service core with a "
                "storage seam, wrapped by an adaptable API/CLI layer."
            ),
            components=[
                "Service core — validation and business logic",
                "Storage seam — in-memory map, replaceable with a real datastore",
                "Adapter layer — API/CLI wrapper (to be implemented)",
            ],
            data_model=["key/value store placeholder — replace with the real schema"],
            api=[
                ApiEndpoint("POST", "/handle", "Handle a request",
                            request="{key, value}", response="{ok, data}", status=200),
            ],
            decisions=[
                "Separate a testable core from transport so logic is unit-testable.",
                "Keep persistence behind a seam to defer the datastore decision.",
            ],
            tradeoffs=[
                "A generic scaffold trades domain specificity for broad applicability; "
                "the core must be filled in for the concrete problem.",
            ],
        )

    def code(self, analysis: AnalysisResult, architecture: Architecture) -> list[Artifact]:
        return [
            Artifact("app/__init__.py", _INIT, "code"),
            Artifact("app/core.py", _CORE, "code"),
        ]

    def tests(
        self,
        analysis: AnalysisResult,
        architecture: Architecture,
        code: list[Artifact],
    ) -> list[Artifact]:
        return [Artifact("tests/test_core.py", _TEST_CORE, "test")]

    def docs(self, analysis: AnalysisResult, architecture: Architecture) -> list[Artifact]:
        return [
            Artifact("README.md", _README, "docs"),
            Artifact("docs/ARCHITECTURE.md", _ARCH, "docs"),
        ]
