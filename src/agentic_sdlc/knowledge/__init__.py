from __future__ import annotations

from dataclasses import dataclass
from typing import Any


class ValidationError(ValueError):
    """Raised when an inbound request fails validation."""


@dataclass
class Result:
    ok: bool
    data: Any = None
    error: str = ""


class Service:
    """Thin, testable core. The API/CLI layer should adapt onto this class."""

    def __init__(self, store: dict | None = None) -> None:
        self._store: dict = store if store is not None else {}

    def handle(self, request: dict) -> Result:
        if not isinstance(request, dict):
            raise ValidationError("request must be a mapping")
        key = request.get("key")
        if not key:
            raise ValidationError("request.key is required")
        self._store[key] = request.get("value")
        return Result(ok=True, data={"key": key})

    def get(self, key: str) -> Result:
        if key not in self._store:
            return Result(ok=False, error="not found")
        return Result(ok=True, data=self._store[key])
